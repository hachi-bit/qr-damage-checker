const LEVEL_INDEX = { L: 0, M: 1, Q: 2, H: 3 };

// マイクロQRコード M1〜M4
// 総コードワード数と、誤り訂正レベルごとの誤り訂正コードワード数（ブロックは常に1つ）
// M1 は誤り検出のみで、誤り訂正レベルの指定がない
const MICRO_TABLE = {
  1: { total: 5, ecc: { '': 2, L: 2 } },
  2: { total: 10, ecc: { L: 5, M: 6 } },
  3: { total: 17, ecc: { L: 6, M: 8 } },
  4: { total: 24, ecc: { L: 8, M: 10, Q: 14 } },
};

/**
 * 誤り訂正ブロック構成を返す。分からない場合は null。
 * @param {'QR'|'MicroQR'} kind
 * @param {number} version
 * @param {string} level L/M/Q/H
 * @returns {{totalCodewords:number, blocks:number, eccPerBlock:number} | null}
 */
export function getBlockInfo(kind, version, level) {
  if (kind === 'QR') {
    const row = QR_TABLE[version - 1];
    const i = LEVEL_INDEX[level];
    if (!row || i === undefined) return null;
    return { totalCodewords: row[0], blocks: row[1 + i * 2], eccPerBlock: row[2 + i * 2] };
  }
  if (kind === 'MicroQR') {
    const m = MICRO_TABLE[version];
    const ecc = m && m.ecc[level];
    if (!ecc) return null;
    return { totalCodewords: m.total, blocks: 1, eccPerBlock: ecc };
  }
  return null;
}
